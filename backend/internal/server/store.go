type User struct {
	Username      string `json:"username,omitempty"`
	Language      string `json:"language"`
	ID            string `json:"id"`
	GoogleSub     string `json:"-"`
	Email         string `json:"email"`
	EmailVerified bool   `json:"emailVerified"`
	Name          string `json:"name"`
	AvatarURL     string `json:"avatarUrl"`
	Locale        string `json:"locale"`
	LoginIP       string `json:"loginIp"`
	LoginIPSource string `json:"loginIpSource"`
	LoginPeerIP   string `json:"loginPeerIp"`
	CreatedAt     string `json:"createdAt"`
	LastLoginAt   string `json:"lastLoginAt"`
}
type Proxy struct {
	ProfileID string          `json:"profileId,omitempty"`
	Name      string          `json:"name,omitempty"`
	NodeID    string          `json:"nodeId,omitempty"`
	Node      json.RawMessage `json:"node,omitempty"`
	Protocol  string          `json:"protocol"`
	Host      string          `json:"host"`
	Port      int             `json:"port"`
	Username  string          `json:"username"`
	Password  string          `json:"password"`
}

func (p Proxy) Valid() bool {
	if p.ProfileID != "" && !regexp.MustCompile(`^[a-fA-F0-9]{8}-(?:[a-fA-F0-9]{4}-){3}[a-fA-F0-9]{12}$`).MatchString(p.ProfileID) {
		return false
	}
	if p.Port < 1 || p.Port > 65535 || len(p.Username) >= 1024 || len(p.Password) >= 4096 {
		return false
	}
	if p.Protocol == "http" || p.Protocol == "https" || p.Protocol == "socks5" {
		return net.ParseIP(p.Host) != nil && len(p.Node) == 0
	}
	if p.Protocol != "vless" && p.Protocol != "hysteria2" && p.Protocol != "ss" {
		return false
	}
	if len(p.Node) > 32768 || len(p.NodeID) != 64 || len(p.Name) > 480 {
		return false
	}
	if net.ParseIP(p.Host) == nil && !regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9.-]{0,252}$`).MatchString(p.Host) {
		return false
	}
	var n struct {
		Type   string `json:"type"`
		Server string `json:"server"`
		Port   int    `json:"port"`
	}
	return json.Unmarshal(p.Node, &n) == nil && n.Type == p.Protocol && n.Server == p.Host && n.Port == p.Port
}

type Store struct {
	DB   *sql.DB
	aead cipher.AEAD
}

func randomToken() string {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return base64.RawURLEncoding.EncodeToString(b)
}
func hash(s string) string { b := sha256.Sum256([]byte(s)); return hex.EncodeToString(b[:]) }
func OpenStore(databaseURL, directory, keyText string) (*Store, error) {
	if databaseURL == "" {
		return nil, errors.New("DATABASE_URL is required (PostgreSQL)")
	}
	if err := os.MkdirAll(directory, 0700); err != nil {
		return nil, err
	}
	var key []byte
	var err error
	if keyText != "" {
		key, err = base64.StdEncoding.DecodeString(keyText)
	} else {
		keyFile := filepath.Join(directory, "encryption.key")
		key, err = os.ReadFile(keyFile)
		if os.IsNotExist(err) {
			key = make([]byte, 32)
			_, err = rand.Read(key)
			if err == nil {
				err = os.WriteFile(keyFile, key, 0600)
			}
		}
	}
	if err != nil || len(key) != 32 {
		return nil, errors.New("encryption key must be 32 bytes")
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, err
	}
	config, err := pgx.ParseConfig(databaseURL)
	if err != nil {
		return nil, errors.New("invalid PostgreSQL configuration")
	}
	config.ConnectTimeout = 5 * time.Second
	config.RuntimeParams["statement_timeout"] = "10000"
	config.RuntimeParams["lock_timeout"] = "5000"
	config.RuntimeParams["idle_in_transaction_session_timeout"] = "10000"
	db := stdlib.OpenDB(*config)
	db.SetMaxOpenConns(10)
	db.SetMaxIdleConns(5)
	db.SetConnMaxLifetime(30 * time.Minute)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err = db.PingContext(ctx); err != nil {
		db.Close()
		return nil, errors.New("cannot connect to PostgreSQL")
	}
	_, err = db.ExecContext(ctx, `
 CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,google_sub TEXT UNIQUE NOT NULL,email TEXT NOT NULL,name TEXT NOT NULL,profile TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS password_credentials(username TEXT PRIMARY KEY,user_id TEXT UNIQUE NOT NULL REFERENCES users(id),password_hash TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires BIGINT NOT NULL);
 CREATE TABLE IF NOT EXISTS login_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),ip TEXT NOT NULL,peer_ip TEXT NOT NULL,ip_source TEXT NOT NULL,user_agent TEXT NOT NULL,created_at TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS proxies(user_id TEXT PRIMARY KEY REFERENCES users(id),config BYTEA NOT NULL,updated_at TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS chat_objects(user_id TEXT NOT NULL REFERENCES users(id),environment TEXT NOT NULL,object_id TEXT NOT NULL,payload BYTEA NOT NULL,PRIMARY KEY(user_id,environment,object_id));
 CREATE TABLE IF NOT EXISTS chat_states(user_id TEXT PRIMARY KEY REFERENCES users(id),revision BIGINT NOT NULL,payload BYTEA NOT NULL,updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
 CREATE TABLE IF NOT EXISTS user_settings(user_id TEXT PRIMARY KEY REFERENCES users(id),settings JSONB NOT NULL);
 CREATE TABLE IF NOT EXISTS browser_cookies(user_id TEXT NOT NULL REFERENCES users(id),environment TEXT NOT NULL,revision BIGINT NOT NULL,payload BYTEA NOT NULL,PRIMARY KEY(user_id,environment));
 CREATE TABLE IF NOT EXISTS runtime_registries(user_id TEXT NOT NULL REFERENCES users(id),host_name TEXT NOT NULL,registry JSONB NOT NULL,PRIMARY KEY(user_id,host_name));
 CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON sessions(user_id);
 CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions(expires);
 CREATE INDEX IF NOT EXISTS login_events_user_id_idx ON login_events(user_id);`)
	if err != nil {
		db.Close()
		return nil, err
	}
	return &Store{DB: db, aead: aead}, nil
}
func (s *Store) Login(u User, ip, peer, source, agent string) (User, string, error) {
	tx, err := s.DB.Begin()
	if err != nil {
		return u, "", err
	}
	defer tx.Rollback()
	// Serialize logins for the same Google subject across all service instances.
	if _, err = tx.Exec("SELECT pg_advisory_xact_lock(hashtextextended($1, 0))", u.GoogleSub); err != nil {
		return u, "", err
	}
	var old string
	err = tx.QueryRow("SELECT profile FROM users WHERE google_sub=$1", u.GoogleSub).Scan(&old)
	if err == nil {
		var previous User
		json.Unmarshal([]byte(old), &previous)
		u.ID = previous.ID
		u.CreatedAt = previous.CreatedAt
	} else if err == sql.ErrNoRows {
		u.ID = randomToken()
		u.CreatedAt = time.Now().UTC().Format(time.RFC3339)
	} else {
		return u, "", err
	}
	u.LoginIP = ip
	u.LoginPeerIP = peer
	u.LoginIPSource = source
	u.LastLoginAt = time.Now().UTC().Format(time.RFC3339)
	profile, _ := json.Marshal(u)
	if _, err = tx.Exec("INSERT INTO users VALUES($1,$2,$3,$4,$5) ON CONFLICT(google_sub) DO UPDATE SET email=excluded.email,name=excluded.name,profile=excluded.profile", u.ID, u.GoogleSub, u.Email, u.Name, string(profile)); err != nil {
		return u, "", err
	}
	token := randomToken()
	if _, err = tx.Exec("INSERT INTO sessions VALUES($1,$2,$3)", hash(token), u.ID, time.Now().Add(30*24*time.Hour).Unix()); err != nil {
		return u, "", err
	}
	if _, err = tx.Exec("INSERT INTO login_events(user_id,ip,peer_ip,ip_source,user_agent,created_at) VALUES($1,$2,$3,$4,$5,$6)", u.ID, ip, peer, source, agent, u.LastLoginAt); err != nil {
		return u, "", err
	}
	return u, token, tx.Commit()
}
func (s *Store) Session(token string) (User, error) {
	var u User
	var profile string
	err := s.DB.QueryRow("SELECT users.profile FROM sessions JOIN users ON users.id=sessions.user_id WHERE token_hash=$1 AND expires>$2", hash(token), time.Now().Unix()).Scan(&profile)
	if err == nil {
		err = json.Unmarshal([]byte(profile), &u)
	}
	if err == nil {
		err = s.applySettings(&u)
	}
	return u, err
}
func (s *Store) Logout(token string) error {
	_, err := s.DB.Exec("DELETE FROM sessions WHERE token_hash=$1", hash(token))
	return err
}
func (s *Store) SaveProxy(userID string, p Proxy) error {
	if !p.Valid() {
		return errors.New("invalid proxy")
	}
	data, _ := json.Marshal(p)
	nonce := make([]byte, s.aead.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return err
	}
	ciphertext := s.aead.Seal(nonce, nonce, data, []byte(userID))
	_, err := s.DB.Exec("INSERT INTO proxies VALUES($1,$2,$3) ON CONFLICT(user_id) DO UPDATE SET config=excluded.config,updated_at=excluded.updated_at", userID, ciphertext, time.Now().UTC().Format(time.RFC3339))
	return err
}
func (s *Store) Proxy(userID string) (*Proxy, error) {
	var encrypted []byte
	err := s.DB.QueryRow("SELECT config FROM proxies WHERE user_id=$1", userID).Scan(&encrypted)
	if err == sql.ErrNoRows {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	n := s.aead.NonceSize()
	if len(encrypted) < n {
		return nil, errors.New("invalid encrypted data")
	}
	data, err := s.aead.Open(nil, encrypted[:n], encrypted[n:], []byte(userID))
	if err != nil {
		return nil, err
	}
	var p Proxy
	err = json.Unmarshal(data, &p)
	return &p, err
}
