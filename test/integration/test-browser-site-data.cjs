// Run: node_modules/.bin/electron test/integration/test-browser-site-data.cjs
// Uses isolated temporary profiles, memory partitions and a loopback-only HTTP fixture.
const {app,session,BrowserWindow}=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const http=require('node:http');
const root=require('node:fs').mkdtempSync(path.join(os.tmpdir(),'kuneco-site-data-'));
app.setPath('userData',root);
app.on('window-all-closed',()=>{});
let server;const windows=[];const managers=[];const syncs=[];
const timeout=setTimeout(()=>{console.error('Timed out');app.exit(1);},45000);
async function run(){
 await app.whenReady();
 const {BrowserSiteData}=await import('../../src/features/browser/browser-site-data.mjs');
 const {BrowserCookieSync}=await import('../../src/features/browser/browser-cookies.mjs');
 server=http.createServer((req,res)=>{res.writeHead(200,{'Content-Type':'text/html','Cache-Control':'max-age=3600'});res.end('<!doctype html><title>Local storage fixture</title>');});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin='http://127.0.0.1:'+server.address().port;
 const storage=session.fromPartition('site-data-target'),other=session.fromPartition('site-data-other');
 for(const ses of [storage,other])await ses.setProxy({mode:'direct'});
 function manager(ses,name){const sites=new BrowserSiteData({storage:ses,file:path.join(root,name+'.json')});managers.push(sites);const sync=new BrowserCookieSync({storage:ses,valid:()=>true,request:async()=>{throw Error('Local mode must not use network');}});syncs.push(sync);return {sites,sync};}
 const {sites,sync}=manager(storage,'target');
 const window=new BrowserWindow({show:false,webPreferences:{session:storage,sandbox:true}});windows.push(window);
 await window.loadURL(origin);
 await window.webContents.executeJavaScript(`(async()=>{localStorage.setItem('fixture','present');await new Promise((resolve,reject)=>{const r=indexedDB.open('fixture',1);r.onupgradeneeded=()=>r.result.createObjectStore('data');r.onsuccess=()=>{r.result.close();resolve()};r.onerror=()=>reject(r.error)});})()`);
 await sites.record(origin);
 const cookie=async(ses,host,value,domain)=>ses.cookies.set({url:'http://'+host+'/',name:'same',value,path:'/',...(domain?{domain}:{})});
 await cookie(storage,'sub.example.test','child');
 await cookie(storage,'example.test','parent','.example.test');
 await cookie(storage,'other.test','other');
 await cookie(other,'sub.example.test','other-partition');
 const initial=await storage.cookies.get({});
 await sites.clear({kind:'cache'},sync);
 assert.deepEqual(await storage.cookies.get({}),initial,'cache-only preserves every cookie');
 assert.equal(await window.webContents.executeJavaScript(`localStorage.getItem('fixture')`),'present');
 console.log('PASS cache-only preserves cookies and localStorage');
 await sites.clear({kind:'site',domain:'sub.example.test'},sync);
 const after=await storage.cookies.get({});
 assert(!after.some(c=>c.domain==='sub.example.test'),'child host cookie removed');
 assert(after.some(c=>c.domain==='.example.test'&&c.value==='parent'),'shared parent same-name cookie preserved');
 assert(after.some(c=>c.domain==='other.test'),'unrelated host preserved');
 console.log('PASS exact-host cookie deletion preserves shared parent and unrelated host');
 window.destroy();
 await sites.clear({kind:'site',domain:'127.0.0.1'},sync);
 const reopened=new BrowserWindow({show:false,webPreferences:{session:storage,sandbox:true}});windows.push(reopened);await reopened.loadURL(origin);
 assert.equal(await reopened.webContents.executeJavaScript(`localStorage.getItem('fixture')`),null);
 assert.deepEqual(await reopened.webContents.executeJavaScript(`indexedDB.databases().then(items=>items.map(item=>item.name))`),[]);
 console.log('PASS recorded-origin localStorage and IndexedDB removed');
 reopened.destroy();
 await sites.clear({kind:'all'},sync);
 assert.deepEqual(await storage.cookies.get({}),[]);
 assert.equal((await other.cookies.get({}))[0].value,'other-partition');
 console.log('PASS clear-all isolates target partition');
 await cookie(storage,'failure.test','keep-local');
 sync.mode='account';sync.started=true;
 let remoteCalls=0;sync.request=async body=>{remoteCalls++;if(body)throw Error('simulated cloud write failure');return {revision:1,payload:[]};};
 await assert.rejects(sites.clear({kind:'all'},sync),/simulated cloud write failure/);
 assert.equal((await storage.cookies.get({}))[0].value,'keep-local','cloud PUT failure cannot modify local cookies');
 assert.equal(remoteCalls,2);
 console.log('PASS failed cloud clear preserves local cookies');
 sync.request=async body=>body?{revision:2}:{revision:1,payload:await storage.cookies.get({})};
 await sites.clear({kind:'all'},sync);
 assert.deepEqual(await storage.cookies.get({}),[]);
 console.log('PASS successful cloud clear removes local cookies');
 await cookie(storage,'sub.example.test','remove-root');
 await cookie(storage,'example.test','keep-parent','.example.test');
 await storage.cookies.set({url:'http://sub.example.test/nested',name:'same',value:'keep-nested',path:'/nested'});
 const remote=(await storage.cookies.get({})).filter(c=>!(c.domain==='sub.example.test'&&c.path==='/'));
 sync.dirty.clear();clearTimeout(sync.timer);
 sync.request=async body=>{assert.equal(body,undefined);return {revision:4,payload:remote};};
 await sync.sync();
 const reconciled=await storage.cookies.get({});
 assert(!reconciled.some(c=>c.domain==='sub.example.test'&&c.path==='/'));
 assert(reconciled.some(c=>c.domain==='sub.example.test'&&c.path==='/nested'&&c.value==='keep-nested'));
 assert(reconciled.some(c=>c.domain==='.example.test'&&c.value==='keep-parent'));
 console.log('PASS cloud reconciliation preserves same-name parent-domain and other-path cookies');
}
run().then(()=>finish(0),error=>{console.error(error);return finish(1);});
async function finish(code){clearTimeout(timeout);for(const sync of syncs)clearTimeout(sync.timer);for(const sites of managers){clearTimeout(sites.timer);await sites.writeQueue.catch(()=>{});}for(const win of windows)if(!win.isDestroyed())win.destroy();if(server)await new Promise(resolve=>server.close(resolve));await fs.rm(root,{recursive:true,force:true});app.exit(code);}
